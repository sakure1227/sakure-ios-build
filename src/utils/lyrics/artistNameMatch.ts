/**
 * 歌手名的**匹配用**归一化：只留下字母、数字与汉字。
 *
 * 为什么需要：同一位歌手在不同地方写法不一样 —— 平台搜索结果里是逗号分隔
 * （`甲,乙`），歌单里是顿号（`甲、乙`），还有 `&` 与 `/` 的差别。
 * 带分隔符去比就对不上，歌词匹配的分数会掉到门槛以下，于是**本来找得到的歌词被丢掉**
 * （用户看到的现象是「歌词来源写着某个平台，但没歌词」—— 而那句歌词其实在别的平台上有）。
 *
 * 所以比之前先归一化：分隔符不算差异。
 */
export const normalizeArtistNameForMatch = (name: string): string => (
    name.replace(/[\s,、&/\\|·]+/g, '').toLowerCase()
);
